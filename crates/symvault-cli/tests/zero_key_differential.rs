const INTRO: &[u8] = b"age-encryption.org/v1\n";

/// Pinned Go oracle (a `CGO_ENABLED=0` build of this commit).
const ORACLE_COMMIT: &str = "c069d3f2b17d704525cedc1bd42840cc6a3e9896";

/// One recorded Go session: the observations plus the frozen base vaults.
struct Session {
    obs: Observations,
    go: PathBuf,
    rust: PathBuf,
    init_tree: OnceLock<Value>,
    plain_tree: OnceLock<Value>,
}

impl Session {
    fn begin(test: &str) -> Self {
        let obs = Observations::begin("zero_key_differential", test, Some(ORACLE_COMMIT));
        obs.stable_under(stable_observation);
        let go = obs.binary();
        Self {
            obs,
            go,
            rust: PathBuf::from(RUST),
            init_tree: OnceLock::new(),
            plain_tree: OnceLock::new(),
        }
    }

    /// The vault the Go oracle's `init` made (`plain`: plus `set w/a.password`),
    /// as `{"root": tree, "home": tree}`. `init` generates random keys, so a
    /// capture keeps the committed tree.
    fn base(&self, plain: bool) -> &Value {
        let (cell, key) = if plain {
            (&self.plain_tree, "base:plain")
        } else {
            (&self.init_tree, "base:init")
        };
        cell.get_or_init(|| {
            self.obs.observe_frozen(key, |go| {
                let temp = tempfile::Builder::new()
                    .prefix("symvault-zk-base-")
                    .tempdir()
                    .expect("temp");
                let root = temp.path().join("vault");
                let home = temp.path().join("home");
                fs::create_dir_all(&home).expect("home");
                fs::create_dir_all(&root).expect("vault root");
                let init = run(
                    go,
                    &root,
                    &home,
                    Some(INIT_PASS),
                    &["init", "--auth", "passphrase"],
                    None,
                );
                assert_eq!(init.code, Some(0), "init: {init:?}");
                if plain {
                    let set = run(
                        go,
                        &root,
                        &home,
                        Some(INIT_PASS),
                        &["set", "w/a.password", "--value", "StrongPassword123!"],
                        None,
                    );
                    assert_eq!(set.code, Some(0), "set: {set:?}");
                }
                json!({"root": snapshot_tree(&root), "home": snapshot_tree(&home)})
            })
        })
    }
}

/// A recapture keeps the committed value when only random bytes (re-wrapped
/// identities in the recorded trees) changed.
fn stable_observation(value: &Value) -> Value {
    let mut value = value.clone();
    if let Some(object) = value.as_object_mut() {
        for key in ["trees_after_follow"] {
            if let Some(slot) = object.get_mut(key) {
                *slot = tree_shape(slot);
            }
        }
    }
    value
}

fn tree_shape(value: &Value) -> Value {
    match value {
        Value::Array(items) => Value::Array(items.iter().map(tree_shape).collect()),
        Value::Object(map) => {
            let mut out = serde_json::Map::new();
            for (key, item) in map {
                if key != "b" {
                    out.insert(key.clone(), tree_shape(item));
                }
            }
            Value::Object(out)
        }
        other => other.clone(),
    }
}

/// Files, directories and symlinks below `dir` (relative paths, modes and
/// base64 contents); `.git/hooks` samples are left out.
fn snapshot_tree(dir: &Path) -> Value {
    fn walk(base: &Path, dir: &Path, out: &mut Vec<Value>) {
        let mut paths: Vec<PathBuf> = fs::read_dir(dir)
            .expect("read dir")
            .flatten()
            .map(|entry| entry.path())
            .collect();
        paths.sort();
        for path in paths {
            let meta = fs::symlink_metadata(&path).expect("metadata");
            let relative = path.strip_prefix(base).unwrap().display().to_string();
            if relative.ends_with(".git/hooks") {
                continue;
            }
            let mode = meta.permissions().mode() & 0o7777;
            if meta.file_type().is_symlink() {
                let target = fs::read_link(&path).unwrap().display().to_string();
                out.push(json!({"p": relative, "k": "l", "m": mode, "b": target}));
            } else if meta.is_dir() {
                out.push(json!({"p": relative, "k": "d", "m": mode}));
                walk(base, &path, out);
            } else {
                let bytes = fs::read(&path).expect("read file");
                out.push(json!({"p": relative, "k": "f", "m": mode,
                    "b": base64::engine::general_purpose::STANDARD.encode(bytes)}));
            }
        }
    }
    let mut entries = Vec::new();
    walk(dir, dir, &mut entries);
    Value::Array(entries)
}

/// Recreates a tree written by [`snapshot_tree`] (replacing what is there).
fn install_tree(dir: &Path, tree: &Value) {
    if let Ok(entries) = fs::read_dir(dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if fs::symlink_metadata(&path).is_ok_and(|meta| meta.is_dir()) {
                let _ = fs::remove_dir_all(&path);
            } else {
                let _ = fs::remove_file(&path);
            }
        }
    }
    fs::create_dir_all(dir).expect("tree root");
    for entry in tree.as_array().expect("tree array") {
        let path = dir.join(entry["p"].as_str().expect("path"));
        let mode = u32::try_from(entry["m"].as_u64().expect("mode")).expect("mode bits");
        match entry["k"].as_str().expect("kind") {
            "d" => {
                fs::create_dir_all(&path).expect("tree dir");
                fs::set_permissions(&path, fs::Permissions::from_mode(mode)).expect("dir mode");
            }
            "l" => {
                symlink(entry["b"].as_str().expect("target"), &path).expect("tree symlink");
            }
            _ => {
                let bytes = base64::engine::general_purpose::STANDARD
                    .decode(entry["b"].as_str().expect("content"))
                    .expect("base64");
                fs::write(&path, bytes).expect("tree file");
                fs::set_permissions(&path, fs::Permissions::from_mode(mode)).expect("file mode");
            }
        }
    }
}

fn fixture(name: &str) -> (Vec<u8>, String) {
    let document: Value = serde_json::from_str(FIXTURE).expect("fixture JSON");
    let case = document["zero_key_cases"]
        .as_array()
        .expect("zero_key_cases")
        .iter()
        .find(|case| case["name"] == name)
        .unwrap_or_else(|| panic!("fixture case {name}"));
    let bytes = base64::engine::general_purpose::STANDARD
        .decode(case["ciphertext"].as_str().expect("ciphertext"))
        .expect("base64");
    (
        bytes,
        case["expected_recipient"]
            .as_str()
            .expect("expected_recipient")
            .to_owned(),
    )
}

fn environment(root: &Path, home: &Path, passphrase: Option<&str>) -> Vec<(&'static str, String)> {
    let home = home.display().to_string();
    let mut environment = vec![
        ("PATH", env::var("PATH").unwrap_or_default()),
        ("XDG_CONFIG_HOME", format!("{home}/config")),
        ("XDG_DATA_HOME", format!("{home}/data")),
        ("XDG_CACHE_HOME", format!("{home}/cache")),
        ("HOME", home),
        ("SYMVAULT_VAULT", root.display().to_string()),
        ("SYMVAULT_TEST_KEYRING", "memory".to_owned()),
        ("CI", "1".to_owned()),
    ];
    if let Some(passphrase) = passphrase {
        environment.push(("SYMVAULT_PASSPHRASE", passphrase.to_owned()));
        environment.push(("SYMVAULT_ALLOW_ENV_PASSPHRASE", "1".to_owned()));
    }
    environment
}

#[derive(Debug, PartialEq, Clone, Serialize, Deserialize)]
struct Out {
    code: Option<i32>,
    stdout: String,
    stderr: String,
}

fn normalise(bytes: &[u8], root: &Path, home: &Path) -> String {
    String::from_utf8_lossy(bytes)
        .replace(&root.display().to_string(), "<ROOT>")
        .replace(&home.display().to_string(), "<HOME>")
}

fn run(
    binary: &Path,
    root: &Path,
    home: &Path,
    passphrase: Option<&str>,
    args: &[&str],
    stdin: Option<&[u8]>,
) -> Out {
    run_under(binary, root, home, passphrase, args, stdin, None)
}

fn run_under(
    binary: &Path,
    root: &Path,
    home: &Path,
    passphrase: Option<&str>,
    args: &[&str],
    stdin: Option<&[u8]>,
    umask: Option<&str>,
) -> Out {
    let mut command = match umask {
        Some(mask) => {
            let mut shell = Command::new("/bin/sh");
            shell
                .arg("-c")
                .arg(format!("umask {mask}; exec \"$0\" \"$@\""))
                .arg(binary);
            shell
        }
        None => Command::new(binary),
    };
    let mut child = command
        .args(args)
        .env_clear()
        .envs(environment(root, home, passphrase))
        .stdin(if stdin.is_some() {
            Stdio::piped()
        } else {
            Stdio::null()
        })
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("spawn");
    let writer = stdin.map(|input| {
        let mut pipe = child.stdin.take().expect("stdin");
        let input = input.to_vec();
        thread::spawn(move || {
            let _ = pipe.write_all(&input);
        })
    });
    let output = child.wait_with_output().expect("wait");
    if let Some(writer) = writer {
        writer.join().expect("stdin writer");
    }
    Out {
        code: output.status.code(),
        stdout: normalise(&output.stdout, root, home),
        stderr: normalise(&output.stderr, root, home),
    }
}

/// How `recipients.txt` is arranged.
#[derive(Clone)]
enum Recipients {
    /// The fixture's own recipient, one line.
    Fixture,
    /// These exact bytes (`{R}` becomes the fixture's recipient).
    Text(&'static str),
    Missing,
    /// A symlink to a regular file holding the fixture's recipient.
    Symlink,
}

/// How the vault starts.
#[derive(Clone)]
enum Prep {
    /// A Go vault whose `identity.age` is a zero-key fixture.
    ZeroKey {
        fixture: &'static str,
        recipients: Recipients,
        /// Replaces the fixture bytes.
        identity: Option<fn() -> Vec<u8>>,
    },
    /// A plain Go vault holding `w/a`, with `manifest.age` left, removed or
    /// supplemented by an entry file the manifest does not know.
    Plain(Manifest),
    /// A plain Go vault with `authMethod: touchid`.
    TouchId,
}

#[derive(Clone, Copy)]
enum Manifest {
    Kept,
    Removed,
    OutOfBand,
}

struct Case {
    name: String,
    prep: Prep,
    passphrase: &'static str,
    env_pass: bool,
    args: Vec<&'static str>,
    stdin: Option<Vec<u8>>,
    /// Commands run by Go and then Rust on the vault the case left.
    follow: Vec<(&'static str, Vec<&'static str>)>,
    /// Whether the Go oracle is expected to have rewritten `identity.age`.
    healed: Option<bool>,
    /// An octal `umask` the command runs under (through `sh`), if any.
    umask: Option<&'static str>,
}

fn zero(name: &str, passphrase: &'static str, args: &[&'static str]) -> Case {
    Case {
        name: name.to_owned(),
        prep: Prep::ZeroKey {
            fixture: "historical_zero_key_length_23",
            recipients: Recipients::Fixture,
            identity: None,
        },
        passphrase,
        env_pass: true,
        args: args.to_vec(),
        stdin: None,
        follow: Vec::new(),
        healed: None,
        umask: None,
    }
}

impl Case {
    fn healed(mut self, healed: bool) -> Self {
        self.healed = Some(healed);
        self
    }
    fn umask(mut self, umask: &'static str) -> Self {
        self.umask = Some(umask);
        self
    }
    fn follow(mut self, passphrase: &'static str, args: &[&'static str]) -> Self {
        self.follow.push((passphrase, args.to_vec()));
        self
    }
    fn recipients(mut self, recipients: Recipients) -> Self {
        if let Prep::ZeroKey {
            recipients: slot, ..
        } = &mut self.prep
        {
            *slot = recipients;
        }
        self
    }
    fn fixture(mut self, name: &'static str) -> Self {
        if let Prep::ZeroKey { fixture: slot, .. } = &mut self.prep {
            *slot = name;
        }
        self
    }
    fn stdin(mut self, input: &[u8]) -> Self {
        self.stdin = Some(input.to_vec());
        self.env_pass = false;
        self
    }
}

/// Everything a binary left behind.
#[derive(Debug, PartialEq)]
struct Observed {
    out: Out,
    /// Relative path → mode (`.git` excluded).
    files: BTreeMap<String, u32>,
    identity_rewritten: bool,
    backup_is_original: Option<bool>,
    follow: Vec<Out>,
}

/// Declared D1 difference (DIST-005): Rust takes a verified backup before the
/// first mutation of an unmarked vault, so a Rust run leaves the `.symvault-rust`
/// marker in the vault and the archive below `$HOME/.local/state/symvault`.
/// Go does neither; the data-safety contract
/// (`make data-safety-differential`) verifies them, so the Go-parity tree
/// comparisons look past exactly these paths.
fn d1_artifact(path: &std::path::Path) -> bool {
    if path
        .file_name()
        .is_some_and(|name| name == ".symvault-rust")
    {
        return true;
    }
    let text = path.to_string_lossy();
    // `.git/info/exclude` keeps the marker out of `git add --all`; Go-created
    // repositories have no `.git/info`.
    if text.ends_with("/.git/info/exclude") || text.ends_with("/.git/info") {
        return true;
    }
    if text.ends_with(".local/state/symvault") || text.contains(".local/state/symvault/") {
        return true;
    }
    // `.local` and `.local/state` exist only because the backup created them.
    let only = |dir: &std::path::Path, child: &str| {
        std::fs::read_dir(dir).is_ok_and(|entries| {
            let names: Vec<_> = entries.flatten().map(|e| e.file_name()).collect();
            names.len() == 1 && names[0] == child
        })
    };
    (text.ends_with("/.local") && only(path, "state") && only(&path.join("state"), "symvault"))
        || (text.ends_with("/.local/state") && only(path, "symvault"))
}

fn walk(dir: &Path, base: &Path, out: &mut BTreeMap<String, u32>) {
    for entry in fs::read_dir(dir).expect("read dir").flatten() {
        let path = entry.path();
        if path.file_name().is_some_and(|name| name == ".git") || d1_artifact(&path) {
            continue;
        }
        let meta = fs::symlink_metadata(&path).expect("metadata");
        let relative = path.strip_prefix(base).unwrap().display().to_string();
        if meta.is_dir() {
            walk(&path, base, out);
        } else {
            out.insert(relative, meta.permissions().mode() & 0o7777);
        }
    }
}

fn exact_header(total: usize, tail: &[u8], filler: u8) -> Vec<u8> {
    // INTRO, a scrypt stanza whose argument line is padded so the header,
    // closing line included, is `total + delta` bytes.
    let mac = vec![b'A'; 43];
    let prefix = b"-> scrypt AAAAAAAAAAAAAAAAAAAAAA 15 ";
    let footer = [b"--- ".as_slice(), &mac, b"\n"].concat();
    let fixed = INTRO.len() + prefix.len() + 1 + tail.len() + footer.len();
    let pad = total.saturating_sub(fixed);
    [INTRO, prefix, &vec![filler; pad], b"\n", tail, &footer].concat()
}

const MIB2: usize = 2 << 20;

fn header_at(delta: isize) -> Vec<u8> {
    exact_header(MIB2.checked_add_signed(delta).unwrap(), b"AAAA\n", b'z')
}

fn scrypt_shaped_lines(lines: usize) -> Vec<u8> {
    let mut data = [INTRO, b"-> scrypt AAAAAAAAAAAAAAAAAAAAAA 15\n"].concat();
    for _ in 0..lines {
        data.extend_from_slice(&[b'A'; 64]);
        data.push(b'\n');
    }
    data.extend_from_slice(b"AAAA\n--- ");
    data.extend_from_slice(&[b'A'; 43]);
    data.push(b'\n');
    data
}

/// Installs the frozen Go-made base vault below `parent` and applies the case.
fn prepare(session: &Session, parent: &Path, case: &Case) -> (PathBuf, PathBuf, Vec<u8>) {
    let root = parent.join("vault");
    let home = parent.join("home");
    fs::create_dir_all(&home).expect("home");
    fs::create_dir_all(&root).expect("vault root");
    let base = session.base(matches!(case.prep, Prep::Plain(_)));
    install_tree(&root, &base["root"]);
    install_tree(&home, &base["home"]);
    let original = match &case.prep {
        Prep::ZeroKey {
            fixture: name,
            recipients,
            identity,
        } => {
            let (bytes, recipient) = fixture(name);
            let bytes = identity.map_or(bytes, |make| make());
            fs::write(root.join("identity.age"), &bytes).expect("identity.age");
            let path = root.join("recipients.txt");
            let _ = fs::remove_file(&path);
            match recipients {
                Recipients::Fixture => fs::write(&path, format!("{recipient}\n")),
                Recipients::Text(text) => fs::write(&path, text.replace("{R}", &recipient)),
                Recipients::Missing => Ok(()),
                Recipients::Symlink => {
                    fs::write(root.join("real-recipients.txt"), format!("{recipient}\n"))
                        .and_then(|()| symlink(root.join("real-recipients.txt"), &path))
                }
            }
            .expect("recipients.txt");
            bytes
        }
        Prep::Plain(manifest) => {
            match manifest {
                Manifest::Kept => {}
                Manifest::Removed => fs::remove_file(root.join("manifest.age")).expect("manifest"),
                Manifest::OutOfBand => {
                    let entries = root.join("entries/w");
                    let source = fs::read_dir(&entries)
                        .expect("entries")
                        .flatten()
                        .next()
                        .expect("entry file")
                        .path();
                    fs::copy(&source, entries.join("zz-copy.age")).expect("copy");
                }
            }
            Vec::new()
        }
        Prep::TouchId => {
            let path = root.join("config.yaml");
            let config = fs::read_to_string(&path).expect("config");
            fs::write(
                &path,
                config.replace("authMethod: passphrase", "authMethod: touchid"),
            )
            .expect("config");
            Vec::new()
        }
    };
    (root, home, original)
}

/// Everything one binary left behind on a freshly prepared vault. Returns the
/// observation and, when the case has follow-ups, nothing else to run here.
fn observe_run(
    session: &Session,
    binary: &Path,
    parent: &Path,
    case: &Case,
) -> (PathBuf, PathBuf, Observed) {
    let (root, home, original) = prepare(session, parent, case);
    let out = run_under(
        binary,
        &root,
        &home,
        case.env_pass.then_some(case.passphrase),
        &case.args,
        case.stdin.as_deref(),
        case.umask,
    );
    let mut files = BTreeMap::new();
    walk(&root, &root, &mut files);
    let identity_rewritten = !original.is_empty()
        && fs::read(root.join("identity.age")).is_ok_and(|now| now != original);
    let backup_is_original = fs::read(root.join("identity.age.bak"))
        .ok()
        .map(|backup| backup == original);
    (
        root,
        home,
        Observed {
            out,
            files,
            identity_rewritten,
            backup_is_original,
            follow: Vec::new(),
        },
    )
}

/// The Go side of a case, exactly as recorded: the run, the files it left, the
/// Go follow-up answers and the vault after the run / after each Go follow-up.
fn record_go(session: &Session, go: &Path, parent: &Path, case: &Case) -> Value {
    let (root, home, observed) = observe_run(session, go, parent, case);
    let mut follow_go = Vec::new();
    let mut trees_after_follow = Vec::new();
    for (passphrase, args) in &case.follow {
        follow_go.push(run(go, &root, &home, Some(passphrase), args, None));
        trees_after_follow.push(snapshot_tree(&root));
    }
    json!({
        "out": observed.out,
        "files": observed.files,
        "identity_rewritten": observed.identity_rewritten,
        "backup_is_original": observed.backup_is_original,
        "follow_go": follow_go,
        "trees_after_follow": trees_after_follow,
    })
}

/// Rebuilds the Go `Observed` from its record. Follow-ups run Go first, then
/// Rust, on the same vault: the Go answer is the recorded one, the Rust
/// follow-up runs live on the recorded Go-healed vault.
fn go_observed(session: &Session, record: &Value, parent: &Path, case: &Case) -> Observed {
    let mut observed = Observed {
        out: serde_json::from_value(record["out"].clone()).expect("recorded Go output"),
        files: serde_json::from_value(record["files"].clone()).expect("recorded Go files"),
        identity_rewritten: record["identity_rewritten"].as_bool().expect("flag"),
        backup_is_original: record["backup_is_original"].as_bool(),
        follow: Vec::new(),
    };
    if case.follow.is_empty() {
        return observed;
    }
    let (root, home, _) = prepare(session, parent, case);
    for (index, (passphrase, args)) in case.follow.iter().enumerate() {
        let go_answer: Out = serde_json::from_value(record["follow_go"][index].clone())
            .expect("recorded Go follow-up");
        install_tree(&root, &record["trees_after_follow"][index]);
        observed.follow.push(go_answer);
        observed.follow.push(run(
            &session.rust,
            &root,
            &home,
            Some(passphrase),
            args,
            None,
        ));
    }
    observed
}

/// Rust on its own prepared vault; the Go follow-up answers come from the Go
/// session (the live Go-on-Rust-vault direction is capture-only).
fn rust_observed(session: &Session, record: &Value, parent: &Path, case: &Case) -> Observed {
    let (root, home, mut observed) = observe_run(session, &session.rust, parent, case);
    for (index, (passphrase, args)) in case.follow.iter().enumerate() {
        let go_answer = if session.obs.capturing() {
            run(&session.go, &root, &home, Some(passphrase), args, None)
        } else {
            serde_json::from_value(record["follow_go"][index].clone())
                .expect("recorded Go follow-up")
        };
        observed.follow.push(go_answer);
        observed.follow.push(run(
            &session.rust,
            &root,
            &home,
            Some(passphrase),
            args,
            None,
        ));
    }
    observed
}

fn compare(session: &Session, cases: &[Case], budget_seconds: u64) {
    let mut failures = Vec::new();
    for batch in cases.chunks(4) {
        let results: Vec<_> = thread::scope(|scope| {
            batch
                .iter()
                .map(|case| {
                    scope.spawn(move || {
                        let temp = tempfile::Builder::new()
                            .prefix("symvault-zk-diff-")
                            .tempdir()
                            .expect("temp");
                        let record = session.obs.observe(&case.name, |go| {
                            record_go(session, go, &temp.path().join("rec"), case)
                        });
                        let started = Instant::now();
                        let go_run = go_observed(session, &record, &temp.path().join("go"), case);
                        let rust_run =
                            rust_observed(session, &record, &temp.path().join("rs"), case);
                        (case, go_run, rust_run, started.elapsed().as_secs())
                    })
                })
                .collect::<Vec<_>>()
                .into_iter()
                .map(|handle| handle.join().expect("case thread"))
                .collect()
        });
        for (case, go_run, rust_run, seconds) in results {
            if go_run != rust_run {
                failures.push(format!(
                    "{}\n  go:   {go_run:?}\n  rust: {rust_run:?}",
                    case.name
                ));
            }
            if let Some(healed) = case.healed
                && go_run.identity_rewritten != healed
            {
                failures.push(format!(
                    "{}: the oracle {} identity.age (the case does not exercise what it claims): {go_run:?}",
                    case.name,
                    if healed { "did not rewrite" } else { "rewrote" }
                ));
            }
            if seconds > budget_seconds {
                failures.push(format!("{}: took {seconds} s", case.name));
            }
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {} cases differ:\n{}",
        failures.len(),
        cases.len(),
        failures.join("\n")
    );
    assert!(session.obs.count() > cases.len(), "every case replayed");
}

