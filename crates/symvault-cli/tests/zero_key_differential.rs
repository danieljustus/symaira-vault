/// Opens a pseudo-terminal as stdin, types the scripted chunks once their
/// prompt shows, and reports the exit status and streams.
const PROMPT_DRIVER: &str = r####"import fcntl, json, os, pty, select, subprocess, sys, termios, time
spec = json.load(open(sys.argv[1]))
master, slave = pty.openpty()
proc = subprocess.Popen([spec["binary"]] + spec["args"], env=spec["env"], cwd=spec["cwd"],
                        stdin=slave, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                        start_new_session=True,
                        preexec_fn=lambda: fcntl.ioctl(0, termios.TIOCSCTTY, 0))
os.close(slave)
steps = [tuple(step) for step in spec["steps"]]
err = b""; out = b""; echo = b""
fe, fo = proc.stderr.fileno(), proc.stdout.fileno()
os.set_blocking(fe, False); os.set_blocking(fo, False)
open_fds = {fe, fo}
deadline = time.time() + 60
while open_fds and time.time() < deadline:
    ready, _, _ = select.select(list(open_fds) + [master], [], [], 0.2)
    for fd in ready:
        try:
            data = os.read(fd, 4096)
        except OSError:
            data = b""
        if fd == master:
            echo += data
            continue
        if not data:
            open_fds.discard(fd)
            continue
        if fd == fe:
            err += data
        else:
            out += data
    if steps and steps[0][0].encode() in err.split(b"\n")[-1]:
        time.sleep(0.15)
        try:
            os.write(master, steps[0][1].encode())
        except OSError:
            pass
        steps.pop(0)
if open_fds:
    proc.kill()
proc.wait()
try:
    while select.select([master], [], [], 0.1)[0]:
        data = os.read(master, 4096)
        if not data:
            break
        echo += data
except OSError:
    pass
os.close(master)
print(json.dumps({"rc": proc.returncode, "stdout": out.hex(), "stderr": err.hex(),
                  "echo": echo.hex(), "left": len(steps)}))
"####;

fn run_prompted(session: &Session, binary: &Path, parent: &Path, steps: &[(&str, &str)]) -> Value {
    let case = manifest_case("prompted", Manifest::Kept, &["get", "w/a.password"]);
    let (root, home, _) = prepare(session, parent, &case);
    let spec = json!({
        "binary": binary,
        "args": ["get", "w/a.password"],
        "steps": steps,
        "cwd": parent,
        "env": environment(&root, &home, None).into_iter().collect::<BTreeMap<_, _>>(),
    });
    let spec_path = parent.join("spec.json");
    fs::write(&spec_path, spec.to_string()).expect("spec");
    let driven = Command::new("python3")
        .args(["-I", "-c", PROMPT_DRIVER])
        .arg(&spec_path)
        .output()
        .expect("python3 is required to drive the pty");
    assert!(
        driven.status.success(),
        "prompt driver: {}",
        String::from_utf8_lossy(&driven.stderr)
    );
    let mut value: Value = serde_json::from_slice(&driven.stdout).expect("driver JSON");
    for key in ["stdout", "stderr", "echo"] {
        let hex = value[key].as_str().expect("hex").to_owned();
        let bytes: Vec<u8> = (0..hex.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).expect("hex digit"))
            .collect();
        value[key] = json!(normalise(&bytes, &root, &home));
    }
    value
}

