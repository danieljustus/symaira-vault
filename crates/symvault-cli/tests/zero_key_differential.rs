//! Differential tests against the Go oracle for what `vault.OpenWithPassphrase`
//! does to an `identity.age` the passphrase does not open (SET-004):
//!
//! * the legacy zero-key heal (`tryHealZeroKeyIdentity`): a file written under
//!   the pre-#476 bug wraps the identity with a key that depends only on the
//!   passphrase length, and Go re-wraps it under the real passphrase, keeping
//!   the old bytes as `identity.age.bak`;
//! * its refusals (wrong, missing, symlinked or garbled `recipients.txt`, a
//!   passphrase of the wrong or of an unsupported length);
//! * identity headers around Go's 2 MiB cap, which must fail with Go's text and
//!   without the CPU the `age` crate burns on them;
//! * `Vault.Open` rebuilding a missing or incomplete `manifest.age`;
//! * the `Touch ID skipped` warning and a Ctrl-D at the hidden prompt.
//!
//! Provenance: the zero-key envelopes are the Go-made `zero_key_cases` of
//! `testdata/port/crypto/age-kdf.json` (generated by `scripts/rust-port/cmd/
//! cryptogen` from `cryptopkg.EncryptZeroKeyFixture`, identity `fixed_1`,
//! Argon2id t=1 m=32 p=1, passphrase length 23 and 1024). Every vault is created
//! by the Go oracle's `init`, then given the fixture as `identity.age`; both
//! binaries run on identical copies of it and are compared on exit status,
//! stdout, stderr, the files left behind with their modes, and on a follow-up
//! command run by both binaries on the vault the first one left (a vault healed
//! by Rust must open in Go and the other way round).
//!
//! The Go side (the non-CGO build) was recorded once
//! (`testdata/port/cli-observations/zero_key_differential.json`): the vaults
//! `init`/`set` created (random keys, frozen as trees), every Go run with the
//! files it left, and the Go follow-up answers. Replay installs the recorded
//! Go-made vault, runs the Rust binary live on it and compares; the Rust
//! follow-up runs on the recorded Go-healed vault, so "a vault healed by Go must
//! open in Rust" stays live. The reverse direction (Go opening a vault healed by
//! Rust) needs a live Go and is only exercised by a capture; replay compares the
//! Rust follow-up with the recorded Go answer on the Go-healed vault instead.

