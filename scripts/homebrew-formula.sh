#!/usr/bin/env bash
# Render Formula/symvault.rb for danieljustus/homebrew-tap.
# Usage: scripts/homebrew-formula.sh VERSION CHECKSUMS_FILE
#
# Replaces GoReleaser's deprecated `brews` publisher. Its successor
# (`homebrew_casks`) would turn the CLI into a quarantined cask, and `brews`
# always wrote `version "X"`, which the tap's strict audit rejects as redundant
# with the version in the URL. So no `version` line here.
set -euo pipefail

version="${1:?version}"
checksums="${2:?checksums file}"
base="https://github.com/danieljustus/symaira-vault/releases/download/v${version}"

sha() {
  local file="symaira-vault_${version}_$1.tar.gz" sum
  sum="$(awk -v f="$file" '$2 == f { print $1 }' "$checksums")"
  [ -n "$sum" ] || { echo "missing checksum for $file" >&2; exit 1; }
  printf '      url "%s/%s"\n      sha256 "%s"\n' "$base" "$file" "$sum"
}

darwin_arm64="$(sha darwin_arm64)"
linux_amd64="$(sha linux_amd64)"
linux_arm64="$(sha linux_arm64)"

cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by symaira-vault scripts/homebrew-formula.sh. DO NOT EDIT.
class Symvault < Formula
  desc "Modern CLI password manager with age encryption"
  homepage "https://github.com/danieljustus/symaira-vault"
  license "Apache-2.0"
  version_scheme 1

  on_macos do
    depends_on arch: :arm64
    on_arm do
${darwin_arm64}
    end
  end

  on_linux do
    on_intel do
${linux_amd64}
    end
    on_arm do
${linux_arm64}
    end
  end

  def install
    bin.install "symvault"
    generate_completions_from_executable(bin/"symvault", "completion")
    man1.install Dir["docs/man/*.1"]
  end

  def caveats
    <<~EOS
      Symaira Vault has been installed!

      To get started:
        symvault init                    # Initialize a new vault
        symvault set github.com/username # Add your first entry
        symvault get github.com/username # Retrieve it

      For MCP server setup:
        symvault agent install <name> --config-only

      Documentation: https://github.com/danieljustus/symaira-vault#readme
    EOS
  end

  test do
    system bin/"symvault", "version"
  end
end
EOF
