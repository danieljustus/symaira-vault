#!/usr/bin/env python3
"""Generate crates/symvault-cli/src/config_schema.rs from the Go config structs.

`symvault config set` re-reads the written file with yaml.v3 into the typed
`config.Config` struct; the Rust port needs the same field types to reproduce
yaml.v3's `cannot unmarshal !!int ... into time.Duration` errors. The table is
read from internal/config/{config,schema}.go so it cannot drift silently:

    python3 scripts/rust-port/gen_config_schema.py          # rewrite
    python3 scripts/rust-port/gen_config_schema.py --check  # fail on drift

Only the structs reachable from Config through yaml-tagged fields matter; a
field's Go type is recorded verbatim (`*time.Duration`, `[]string`,
`map[string]AgentProfile`, ...).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = ["internal/config/config.go", "internal/config/schema.go"]
TARGET = ROOT / "crates/symvault-cli/src/config_schema.rs"

STRUCT = re.compile(r"^type (\w+) struct \{\n(.*?)^\}", re.S | re.M)
FIELD = re.compile(r'^\s*\w+\s+(\S+)\s+`yaml:"([^"]*)"`')


def structs():
    found = {}
    for source in SOURCES:
        text = (ROOT / source).read_text()
        for name, body in STRUCT.findall(text):
            fields = []
            for line in body.splitlines():
                line = line.split("//")[0].rstrip() if "`" not in line else line
                match = FIELD.match(line)
                if not match:
                    continue
                go_type, tag = match.groups()
                key = tag.split(",")[0]
                if key in ("", "-"):
                    continue
                fields.append((key, go_type))
            if fields:
                found[name] = fields
    return found


def render(found):
    out = [
        "// @generated by scripts/rust-port/gen_config_schema.py from",
        "// internal/config/config.go and internal/config/schema.go; do not edit.",
        "// `make config-cli-differential` fails when this file drifts from the Go source.",
        "",
        "/// `(struct name, [(yaml key, Go type)])` of every yaml-tagged struct of the",
        "/// Go configuration, the types verbatim (`*time.Duration`, `[]string`, ...).",
        "#[rustfmt::skip]",
        "pub(crate) const GO_CONFIG_STRUCTS: &[(&str, &[(&str, &str)])] = &[",
    ]
    for name in sorted(found):
        out.append(f'    ("{name}", &[')
        for key, go_type in found[name]:
            out.append(f'        ("{key}", "{go_type}"),')
        out.append("    ]),")
    out.append("];")
    return "\n".join(out) + "\n"


def main():
    rendered = render(structs())
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != rendered:
            sys.exit(f"{TARGET.relative_to(ROOT)} is stale; run scripts/rust-port/gen_config_schema.py")
        print(f"PASS {TARGET.relative_to(ROOT)} matches the Go config structs")
        return
    TARGET.write_text(rendered)
    print(f"WROTE {TARGET.relative_to(ROOT)}")


main()
