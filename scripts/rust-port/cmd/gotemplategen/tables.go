package main

import (
	"fmt"
	"strings"
	"unicode"
)

// emitTables writes crates/symvault-sync/src/gotemplate/unicode_tables.rs.
//
// The Rust standard library's character classes differ from Go's `unicode`
// package (IsLetter vs Alphabetic, simple vs full case mapping, Unicode
// version), so the interpreter carries Go's own tables, generated from the
// pinned toolchain.
func emitTables() string {
	var b strings.Builder
	b.WriteString("// Code generated by scripts/rust-port/cmd/gotemplategen --tables; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: Go unicode package, Unicode %s.\n\n", unicode.Version)
	ranges := func(name string, in func(rune) bool) {
		type span struct{ lo, hi rune }
		var spans []span
		for r := rune(0); r <= unicode.MaxRune; r++ {
			if !in(r) {
				continue
			}
			if n := len(spans); n > 0 && spans[n-1].hi+1 == r {
				spans[n-1].hi = r
			} else {
				spans = append(spans, span{r, r})
			}
		}
		fmt.Fprintf(&b, "#[rustfmt::skip]\npub(super) static %s: &[(u32, u32)] = &[", name)
		for i, s := range spans {
			if i%6 == 0 {
				b.WriteString("\n    ")
			} else {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "(0x%X, 0x%X),", s.lo, s.hi)
		}
		b.WriteString("\n];\n\n")
	}
	mapping := func(name string, f func(rune) rune) {
		fmt.Fprintf(&b, "#[rustfmt::skip]\npub(super) static %s: &[(u32, u32)] = &[", name)
		n := 0
		for r := rune(0); r <= unicode.MaxRune; r++ {
			if m := f(r); m != r {
				if n%6 == 0 {
					b.WriteString("\n    ")
				} else {
					b.WriteString(" ")
				}
				fmt.Fprintf(&b, "(0x%X, 0x%X),", r, m)
				n++
			}
		}
		b.WriteString("\n];\n\n")
	}
	ranges("LETTER", unicode.IsLetter)
	ranges("DIGIT", unicode.IsDigit)
	mapping("TO_UPPER", unicode.ToUpper)
	mapping("TO_LOWER", unicode.ToLower)
	return strings.TrimRight(b.String(), "\n") + "\n"
}
