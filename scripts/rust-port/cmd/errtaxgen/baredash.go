package main

import "fmt"

// The bare-dash section (CLI-005). A lone `-` and the `--` terminator reach
// cobra's two argument walks differently, and the pinned CLI shows both:
//
//   - cobra's command resolution (`stripFlags`) skips a token that starts with a
//     dash, so a lone `-` never names a command and never ends the walk: `- list`
//     runs `list`, `share - list` runs `share list`. pflag later counts the `-`
//     as a positional of the resolved command, so `- get x` is a two-argument
//     `get` and `config - get x` a two-argument `config get`.
//   - `--` ends command resolution. With no command before it, the root runs and
//     (it is not runnable) prints its help with exit 0; whatever follows `--`
//     (`list`, `--json`, `--version`, a lone `-`) is a positional of the root that
//     cobra's legacy argument check never sees, so it is not an unknown command.
//   - the same holds for a bare root with only persistent flags (`--json`,
//     `--output xml`): no command, so no output-format gate, only the help.
//   - `help` resolves its topic through the same walk, so `help -` is the root
//     help and `help - list` the help of `list`; an unknown topic is still
//     reported with every word, the dash included.
//
// Commands that read the vault run in both sandbox states; a diagnostic that
// ends before any vault access runs in the uninitialized one only. `completion`
// is deliberately absent: its subcommands are generated by cobra at execute time
// and are not part of the frozen command tree.

type bareDashCase struct {
	slug, description string
	args              []string
	states            []string
}

func bareDashCases() []bareDashCase {
	var cases []bareDashCase
	add := func(slug, description string, args []string, states ...string) {
		if len(states) == 0 {
			states = []string{stateUninitialized}
		}
		cases = append(cases, bareDashCase{slug: slug, description: description, args: args, states: states})
	}
	both := []string{stateUninitialized, stateInitialized}

	// --- no command: the root prints its help ---
	add("root_no_args", "no arguments: the root is not runnable, so it prints its help", []string{})
	add("root_json_only", "a persistent flag alone: no command, so no output-format gate, only the help", []string{"--json"})
	add("root_output_xml_only", "--output xml alone is not gated: the root help", []string{"--output", "xml"})
	add("root_vault_flag_only", "a flag with its value and no command: the root help", []string{"--vault", "somewhere"})
	add("root_quiet_only", "--quiet alone: the root help", []string{"--quiet"})
	add("root_dash", "a lone dash is no command: the root help", []string{"-"})
	add("root_double_dash", "a lone -- ends resolution: the root help", []string{"--"})
	add("root_dash_double_dash", "- then --: the root help", []string{"-", "--"})
	add("root_double_dash_dash", "-- then -: the root help", []string{"--", "-"})
	add("root_two_dashes", "two lone dashes: the root help", []string{"-", "-"})
	add("root_json_then_dash", "--json - : no command, no gate", []string{"--json", "-"})
	add("root_output_xml_then_dash", "--output xml - : no command, no gate", []string{"--output", "xml", "-"})
	add("root_json_double_dash", "--json -- : no command, no gate", []string{"--json", "--"})

	// --- after `--` everything is a positional of the root ---
	add("after_double_dash_command", "-- list: list is not resolved, the root help", []string{"--", "list"})
	add("after_double_dash_command_with_arg", "-- get x: get is not resolved, the root help", []string{"--", "get", "x"})
	add("after_double_dash_group", "-- config list: the root help", []string{"--", "config", "list"})
	add("after_double_dash_help", "-- help: help is not resolved, the root help", []string{"--", "help"})
	add("after_double_dash_dash_command", "-- - list", []string{"--", "-", "list"})
	add("after_double_dash_flag", "-- --json: a flag after -- is a positional", []string{"--", "--json"})
	add("after_double_dash_help_flag", "-- --help: a help flag after -- is a positional", []string{"--", "--help"})
	add("after_double_dash_version_flag", "-- --version: a version flag after -- is a positional", []string{"--", "--version"})
	add("after_double_dash_short_flag", "-- -x: an unknown shorthand after -- is a positional", []string{"--", "-x"})
	add("after_double_dash_unknown_flag", "-- --nonsense: an unknown flag after -- is a positional", []string{"--", "--nonsense"})
	add("after_double_dash_output_xml", "-- --output xml: the gate flag after -- is a positional", []string{"--", "--output", "xml"})
	add("dash_then_double_dash_command", "- -- list", []string{"-", "--", "list"})

	// --- a lone dash before the command ---
	add("dash_before_list", "- list: the dash does not hide the command", []string{"-", "list"}, both...)
	add("dash_before_get_missing_name", "- get: the dash is the only positional, so get has its one argument; the vault check ends the run (an initialized vault would search the entries for `-`, a separate matter)", []string{"-", "get"})
	add("dash_before_get_name", "- get x: two positionals", []string{"-", "get", "x"})
	add("dash_before_list_with_json", "- --json list", []string{"-", "--json", "list"}, both...)
	add("dash_before_list_with_output_yaml", "- --output yaml list", []string{"-", "--output", "yaml", "list"}, both...)
	add("dash_before_list_with_quiet", "- --quiet list", []string{"-", "--quiet", "list"}, both...)
	add("dash_after_vault_flag_value", "--vault - list: the dash is the flag's value", []string{"--vault", "-", "list"})
	add("dash_vault_equals_dash", "--vault=- list", []string{"--vault=-", "list"})
	add("two_dashes_before_list", "- - list: two positionals for list", []string{"-", "-", "list"})
	add("dash_before_list_extra_arg", "- list foo: two positionals for list", []string{"-", "list", "foo"})
	add("dash_before_list_double_dash", "- list --", []string{"-", "list", "--"}, both...)
	add("dash_before_unknown_shorthand", "- -y list: pflag reports the shorthand", []string{"-", "-y", "list"})
	add("dash_before_unknown_command", "- unknownthing: the unknown command is named without the dash", []string{"-", "unknownthing"})
	add("dash_before_unknown_flag", "- --nonsense", []string{"-", "--nonsense"})
	add("dash_before_version_flag", "- --version", []string{"-", "--version"})
	add("dash_before_version", "- version", []string{"-", "version"})
	add("dash_before_version_json", "- version --json", []string{"-", "version", "--json"})
	add("dash_after_version", "version -", []string{"version", "-"})
	add("dash_after_version_then_json", "version - --json: a flag after a positional is still a flag", []string{"version", "-", "--json"})
	add("word_after_version_then_json", "version foo --json: the same without the dash", []string{"version", "foo", "--json"})
	add("dash_after_list", "list -: the dash is the prefix", []string{"list", "-"}, both...)
	add("dash_after_get", "get -: the dash is the entry name; the vault check ends the run (an initialized vault would search the entries for `-`, a separate matter)", []string{"get", "-"})
	add("dash_after_get_twice", "get - -: two positionals", []string{"get", "-", "-"})
	add("dash_between_get_and_name", "get - x: two positionals", []string{"get", "-", "x"})

	// --- groups ---
	add("dash_before_group_list", "- share list", []string{"-", "share", "list"}, both...)
	add("dash_inside_group_list", "share - list: the dash does not hide the subcommand", []string{"share", "-", "list"}, both...)
	add("dash_after_group_list", "share list -", []string{"share", "list", "-"}, both...)
	add("two_dashes_before_group_list", "- - share list", []string{"-", "-", "share", "list"}, both...)
	add("dash_around_group_list", "- share - list", []string{"-", "share", "-", "list"}, both...)
	add("dash_inside_group_only", "share -: a group with a positional prints its help", []string{"share", "-"})
	add("dash_inside_group_two_dashes", "share - -", []string{"share", "-", "-"})
	add("double_dash_inside_group", "share -- list", []string{"share", "--", "list"})
	add("dash_before_config_list", "- config list", []string{"-", "config", "list"})
	add("dash_inside_config_list", "config - list", []string{"config", "-", "list"})
	add("dash_after_config_list", "config list -", []string{"config", "list", "-"})
	add("dash_inside_config_get", "config - get x: two positionals for config get", []string{"config", "-", "get", "x"})
	add("double_dash_before_config", "-- config list", []string{"--", "config", "list"})

	// --- help ---
	add("help_dash", "help -: the topic walk skips the dash, so the root help", []string{"help", "-"})
	add("help_dash_command", "help - list: the help of list", []string{"help", "-", "list"})
	add("help_command_dash", "help list -: the help of list", []string{"help", "list", "-"})
	add("help_two_dashes", "help - -", []string{"help", "-", "-"})
	add("help_unknown_topic_dash", "help foo -: the unknown topic lists every word", []string{"help", "foo", "-"})
	add("help_dash_unknown_topic", "help - foo", []string{"help", "-", "foo"})
	add("dash_before_help", "- help: the root help", []string{"-", "help"})
	add("dash_before_help_command", "- help list: the help of list", []string{"-", "help", "list"})
	add("help_double_dash", "help -- : the root help", []string{"help", "--"})
	add("help_double_dash_command", "help -- list", []string{"help", "--", "list"})
	return cases
}

// bareDashInputs expands bareDashCases to scenario inputs, one per state.
func bareDashInputs() []scenarioInput {
	var out []scenarioInput
	for _, c := range bareDashCases() {
		for _, state := range c.states {
			out = append(out, scenarioInput{
				name:        fmt.Sprintf("dash_%s_%s", c.slug, state),
				description: fmt.Sprintf("%s (%s)", c.description, state),
				state:       state,
				args:        c.args,
			})
		}
	}
	return out
}
